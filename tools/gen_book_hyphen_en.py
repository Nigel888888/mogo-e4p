#!/usr/bin/env python3
"""中文：把固定的英文断词模式压成固件只读前缀树。
English: Pack the pinned English hyphenation patterns into a firmware read-only trie.
"""
import argparse
from hashlib import sha256
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/vendor/hyphen-en-us/hyph-en-us.tex'
OUTPUT = ROOT / 'main/book/book_hyphen_en_data.inc'
SOURCE_SHA256 = 'f4ffcd96c5cbc886bdad23f95dcae8edc3cd3620eae62f7946eceda97c4e68f8'


def generate(data):
    assert sha256(data).hexdigest() == SOURCE_SHA256, 'Unexpected upstream pattern data'
    tex = re.sub(r'%[^\n]*', '', data.decode('ascii'))
    patterns = re.search(r'\\patterns\{([^}]*)\}', tex)[1].split()
    exceptions = re.search(r'\\hyphenation\{([^}]*)\}', tex)[1].split()
    root = ({}, [])
    for pattern in patterns:
        assert re.fullmatch(r'[.a-z1-9]+', pattern), pattern
        node, scores = root, [0]
        for ch in pattern:
            if ch.isdigit():
                scores[-1] = int(ch)
            else:
                node = node[0].setdefault(ch, ({}, []))
                scores.append(0)
        if not node[1]:
            node[1].extend(scores)
        else:
            node[1][:] = map(max, node[1], scores)

    # 子节点按广度顺序连续编号；边只存字母，子节点编号等于边下标。
    # Breadth-first children are contiguous; the incoming edge index is the child node ID.
    nodes, labels, child, values = [root], ['.'], [], []
    weights = [0]
    offsets = {(): 0}
    for children, scores in nodes:
        child.append(len(nodes))
        for label, node in sorted(children.items()):
            nodes.append(node)
            labels.append(label)
        while scores and not scores[-1]:
            scores.pop()
        key = tuple(scores)
        if key not in offsets:
            offsets[key] = len(weights)
            weights.extend([len(key), *key])
        values.append(offsets[key])
    child.append(len(nodes))
    assert max(child + values) <= 65535

    def numbers(kind, name, items):
        rows = ['    ' + ', '.join(map(str, items[i:i+16])) + ',' for i in range(0, len(items), 16)]
        return f'static const {kind} {name}[] = {{\n' + '\n'.join(rows) + '\n};\n'

    license_lines = (
        'Copyright (C) 1990, 2004, 2005 Gerard D.C. Kuiken',
        'Copying and distribution of this file, with or without modification,',
        'are permitted in any medium without royalty provided the copyright',
        'notice and this notice are preserved.',
    )
    attribution = 'Derived from hyph-utf8 hyph-en-us.tex (Kuiken plus the original Plain TeX tables).'
    notice = '/*\n * 自动生成，勿手改。/ Generated by tools/gen_book_hyphen_en.py; do not edit.\n'
    notice += ''.join(f' * {line}\n' for line in (attribution, *license_lines)) + ' */\n'
    embedded = '#ifdef ESP_PLATFORM\nstatic const char s_pattern_notice[] __attribute__((used, retain)) =\n'
    embedded += '\n'.join(f'    "{line}\\n"' for line in (attribution, *license_lines)) + ';\n#endif\n'
    result = [notice, embedded, numbers('uint16_t', 's_child', child), numbers('uint16_t', 's_value', values),
              'static const char s_label[] =\n' + '\n'.join(
                  '    "' + ''.join(labels[i:i+76]) + '"' for i in range(0, len(labels), 76)) + ';\n',
              numbers('uint8_t', 's_weight', weights),
              'static const struct { const char *word; uint64_t breaks; } s_exceptions[] = {\n']
    entries = []
    for word in sorted(exceptions, key=lambda word: word.replace('-', '')):
        assert re.fullmatch(r'[a-z]+(?:-[a-z]+)*', word)
        parts = word.split('-')
        mask = sum(1 << sum(map(len, parts[:i])) for i in range(1, len(parts)))
        entries.append(f'    {{"{"".join(parts)}", UINT64_C({mask})}},')
    result.append('\n'.join(entries) + '\n};\n')
    return '\n'.join(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate(SOURCE.read_bytes())
    if args.check:
        if OUTPUT.read_text() != generated:
            parser.exit(1, 'English hyphenation table is not reproducible; regenerate it.\n')
    else:
        OUTPUT.write_text(generated)
    print('PASS: pinned English hyphenation table' if args.check else f'Generated {OUTPUT}')


if __name__ == '__main__':
    main()
